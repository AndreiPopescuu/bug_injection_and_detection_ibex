"""run_mutation.py -- lightweight mutation testing harness for ibex_decoder.

For each mutant generated by mutator.py:
  1. Points Verilator at the mutant's RTL dir (via RTL_DIR env var the Makefile honors)
  2. Runs the test harness with a chosen CRT profile / LLM module
  3. Captures decoder output signals for each stimulus
  4. Compares against baseline (same stimuli on original RTL)
  5. "KILLED" = any stimulus produced different output signals; else "SURVIVED"

Reuses the existing cocotb test as the stimulus driver and output sampler.
We don't modify the testbench; we add a side-channel JSON dump of
per-stimulus outputs via an env flag the test honors.

Run:
  python3 run_mutation.py --profile pure_random --n 200 --seed 0
  python3 run_mutation.py --profile default --n 500
"""
import argparse
import json
import os
import subprocess
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
MUTANTS_DIR = HERE / "mutants"
RESULTS_DIR = HERE / "mutation_results"


def run_campaign(rtl_dir: Path, profile: str, n: int, seed: int, tag: str,
                 llm_module: str = None, extra_env=None) -> dict:
    """Run `make` with RTL_DIR overridden; return path to dumped signal trace."""
    out_dir = RESULTS_DIR / "runs" / tag
    out_dir.mkdir(parents=True, exist_ok=True)
    env = os.environ.copy()
    env.update({
        "RTL_DIR": str(rtl_dir),
        "CRT_PROFILE": profile,
        "CRT_N": str(n),
        "CRT_SEED": str(seed),
        "CRT_OUT": str(out_dir),
        "PAPER_MODE": env.get("PAPER_MODE", "0"),
        "SIM_BUILD": f"sim_build_mut_{tag}",
        # Hook so the testbench dumps per-stimulus (insn, outputs) to JSON
        "DUMP_SIGNALS": str(out_dir / "signals.json"),
    })
    if llm_module:
        env["LLM_MODULE"] = llm_module
    if extra_env:
        env.update(extra_env)

    t0 = time.time()
    res = subprocess.run(
        ["make"],
        cwd=HERE,
        env=env,
        capture_output=True,
        text=True,
    )
    elapsed = time.time() - t0

    signals_path = out_dir / "signals.json"
    return {
        "tag": tag,
        "rtl": str(rtl_dir),
        "returncode": res.returncode,
        "elapsed": elapsed,
        "signals_file": str(signals_path) if signals_path.exists() else None,
        "stdout_tail": res.stdout[-500:] if res.stdout else "",
        "stderr_tail": res.stderr[-500:] if res.stderr else "",
    }


def load_signals(path: Path) -> list[dict]:
    if not path.exists():
        return []
    return json.loads(path.read_text())


def compare_traces(baseline: list[dict], mutant: list[dict]) -> dict:
    """Return a dict summarizing the first divergence (if any)."""
    if len(baseline) != len(mutant):
        return {"killed": True, "reason": f"trace length differs ({len(baseline)} vs {len(mutant)})",
                "first_mismatch": None}
    for i, (b, m) in enumerate(zip(baseline, mutant)):
        if b["insn"] != m["insn"]:
            return {"killed": True, "reason": "insn stream diverged (unexpected)",
                    "first_mismatch": i}
        diffs = {k: (b[k], m[k]) for k in b if k not in ("insn",) and b.get(k) != m.get(k)}
        if diffs:
            return {"killed": True, "reason": "output signal mismatch",
                    "first_mismatch": i, "insn": f"0x{b['insn']:08x}",
                    "diff_signals": list(diffs.keys())[:5]}
    return {"killed": False, "reason": "no divergence over the stimulus stream",
            "first_mismatch": None}


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--profile", default="pure_random",
                    help="CRT profile (pure_random / default / llm_crt)")
    ap.add_argument("--n", type=int, default=200, help="stimuli per run")
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--only", nargs="*", help="run only these mutant IDs (e.g. m000 m003)")
    ap.add_argument("--llm-module",
                    help="LLM run module for --profile llm_crt "
                         "(e.g. crt.llm_runs.A_run1_p1; can be comma-separated for multi-pass)")
    args = ap.parse_args()

    assert MUTANTS_DIR.exists(), f"No mutants dir -- run `python3 mutator.py` first ({MUTANTS_DIR})"
    mutants = sorted(d for d in MUTANTS_DIR.iterdir()
                     if d.is_dir() and d.name.startswith("m"))
    if args.only:
        mutants = [m for m in mutants if any(m.name.startswith(x) for x in args.only)]
    assert mutants, "No mutants to run"

    RESULTS_DIR.mkdir(exist_ok=True)
    tag_llm = args.llm_module.replace("crt.llm_runs.", "") if args.llm_module else "default"
    print(f"=== Mutation campaign ===")
    print(f"Profile : {args.profile}   N stimuli: {args.n}   Seed: {args.seed}")
    print(f"LLM mod : {args.llm_module or '(makefile default: crt.llm_runs.C_run1_p1)'}")
    print(f"Mutants : {len(mutants)}\n")

    # Baseline on original RTL
    print("[1/{}]  baseline (original RTL)".format(len(mutants) + 1))
    base = run_campaign(HERE / "rtl", args.profile, args.n, args.seed,
                        llm_module=args.llm_module,
                        tag=f"baseline_{args.profile}_{tag_llm}_s{args.seed}")
    if base["returncode"] != 0 or not base["signals_file"]:
        print(f"  !! baseline FAILED (rc={base['returncode']})")
        print(f"  stdout tail: {base['stdout_tail']}")
        print(f"  stderr tail: {base['stderr_tail']}")
        sys.exit(2)
    baseline_trace = load_signals(Path(base["signals_file"]))
    print(f"  ok ({len(baseline_trace)} stimuli, {base['elapsed']:.1f}s)")

    results = []
    for idx, mdir in enumerate(mutants, start=2):
        print(f"[{idx}/{len(mutants)+1}] {mdir.name}")
        run = run_campaign(mdir, args.profile, args.n, args.seed,
                           llm_module=args.llm_module,
                           tag=f"{mdir.name}_{args.profile}_{tag_llm}_s{args.seed}")
        if run["returncode"] != 0 or not run["signals_file"]:
            verdict = {"killed": True, "reason": "build/sim failed",
                       "returncode": run["returncode"]}
            print(f"  BUILD/SIM FAIL (rc={run['returncode']}) -> counted as KILLED")
        else:
            mutant_trace = load_signals(Path(run["signals_file"]))
            verdict = compare_traces(baseline_trace, mutant_trace)
            tag = "KILLED" if verdict["killed"] else "SURVIVED"
            extra = ""
            if verdict["killed"] and "first_mismatch" in verdict and verdict["first_mismatch"] is not None:
                extra = f" @stim#{verdict['first_mismatch']} ({verdict.get('reason','')})"
            print(f"  {tag}{extra}  [{run['elapsed']:.1f}s]")

        results.append({
            "mutant": mdir.name,
            "verdict": verdict,
            "elapsed": run["elapsed"],
        })

    killed = sum(1 for r in results if r["verdict"].get("killed"))
    kill_rate = killed / len(results) if results else 0.0
    report = {
        "profile": args.profile,
        "llm_module": args.llm_module,
        "n": args.n,
        "seed": args.seed,
        "total": len(results),
        "killed": killed,
        "kill_rate": kill_rate,
        "results": results,
    }
    out = RESULTS_DIR / f"report_{args.profile}_{tag_llm}_n{args.n}_s{args.seed}.json"
    out.write_text(json.dumps(report, indent=2))
    print(f"\n=== Summary ===")
    print(f"Kill rate: {killed}/{len(results)} = {100*kill_rate:.1f}%")
    print(f"Report:    {out}")


if __name__ == "__main__":
    main()
